console = Console(highlight=False)

load_dotenv(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docker", ".env"))


class SpecificWorker(GenericWorker):
    def __init__(self, proxy_map, configData, startup_check=False):
        super(SpecificWorker, self).__init__(proxy_map, configData)
        self.Period = configData["Period"]["Compute"]
        if startup_check:
            self.startup_check()
        else:
            # Required Power sources (generated by the "requires Power, Power, Power" in the .cdsl)
            self.power_sources = {
                "Power": self.power_proxy,
                "Power1": self.power1_proxy,
                "Power2": self.power2_proxy,
            }
            self.latestPowers = {}

            # Credentials come from docker/.env (never from etc/config, to
            # avoid leaking them in git-tracked files)
            self.influx_bucket = os.environ["INFLUXDB_BUCKET"]
            self.influx_org = os.environ["INFLUXDB_ORG"]
            self.influx_client = InfluxDBClient(
                url=os.environ.get("INFLUXDB_URL", "http://localhost:8086"),
                token=os.environ["INFLUXDB_TOKEN"],
                org=self.influx_org,
            )
            self.influx_write_api = self.influx_client.write_api(write_options=SYNCHRONOUS)

            self.timer.timeout.connect(self.compute)
            self.timer.start(self.Period)

    def __del__(self):
        """Destructor"""

    @QtCore.Slot()
    def compute(self):
        points = []
        for source_name, proxy in self.power_sources.items():
            try:
                powers = proxy.getPowers()
            except Ice.Exception as e:
                console.print(f"[{source_name}] unreachable: {e}", style="red", markup=False)
                continue

            for p in powers:
                self.latestPowers[p.name] = p
                points.append(
                    Point("power")
                    .tag("source", p.name)
                    .field("voltage", p.voltage)
                    .field("current", p.current)
                    .field("power", p.power)
                    .time(p.timestamp, write_precision=WritePrecision.MS)
                )

        if points:
            try:
                self.influx_write_api.write(bucket=self.influx_bucket, org=self.influx_org, record=points)
            except Exception as e:
                console.print(f"[InfluxDB] write error: {e}", style="red", markup=False)

        return True

    def startup_check(self):
        print(f"Testing RoboCompPower.PowerData from ifaces.RoboCompPower")
        test = ifaces.RoboCompPower.PowerData()
        QTimer.singleShot(200, QApplication.instance().quit)




    # =============== Methods for Component Implements ==================
    # ===================================================================

    #
    # IMPLEMENTATION of getPower method from Power interface
    #
    def Power_getPower(self, name):
        try:
            return self.latestPowers[name]
        except KeyError:
            raise ifaces.RoboCompPower.UnknownSourceException(name=name)

    #
    # IMPLEMENTATION of getPowers method from Power interface
    #
    def Power_getPowers(self):
        return ifaces.RoboCompPower.Powers(self.latestPowers.values())
